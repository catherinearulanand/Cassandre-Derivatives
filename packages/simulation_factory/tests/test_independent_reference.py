"""SIM-008: the independent reference script must be a genuinely separate
code path from anything a product's own aggregation code might do, per
plan Section 9.3's explicit warning against generating expected totals
"using the same implementation under test"."""

from __future__ import annotations

import ast
import inspect
from decimal import Decimal

from simulation_factory.corpus.trades import build_trade_corpus
from simulation_factory.independent_reference import trade_population_reference as ref_module
from simulation_factory.independent_reference.trade_population_reference import (
    compute_source_control_manifest,
)


def test_reference_module_never_imports_riskos_or_any_product():
    tree = ast.parse(inspect.getsource(ref_module))
    imported_names = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            imported_names.update(alias.name.split(".")[0] for alias in node.names)
        elif isinstance(node, ast.ImportFrom) and node.module:
            imported_names.add(node.module.split(".")[0])
    forbidden = {"riskos", "clauseos", "collateralos"}
    assert not (imported_names & forbidden), (
        f"independent reference script must never import a product package, found {imported_names & forbidden}"
    )


def test_reference_module_does_not_import_the_generator_module():
    """The reference script must not depend on `simulation_factory.corpus.trades`
    (the generator) for its bucket-size constants -- it recomputes every
    total from the actual trade sequence instead, so a bug in the
    generator's own bookkeeping cannot silently propagate into "expected"
    totals that would then trivially match."""

    tree = ast.parse(inspect.getsource(ref_module))
    imported_modules = set()
    for node in ast.walk(tree):
        if isinstance(node, ast.ImportFrom) and node.module:
            imported_modules.add(node.module)
    assert "simulation_factory.corpus.trades" not in imported_modules


def test_reference_manifest_matches_a_hand_derived_small_case():
    """A tiny, fully hand-derived case (not generated by `corpus.trades` at
    all), independently computed by eye here in the test, cross-checked
    against the reference script."""

    class _Trade:
        def __init__(self, trade_id, disposition, amount, rejection_reason=None):
            from money_types import Money

            self.trade_id = trade_id
            self.disposition = disposition
            self.rejection_reason = rejection_reason
            self.mtm = Money(amount=amount, currency="USD", rounding_context="TEST")

    trades = [
        _Trade("SIM-TRADE-A", "ACCEPTED", "100.00"),
        _Trade("SIM-TRADE-B", "ACCEPTED", "-40.00"),
        _Trade("SIM-TRADE-C", "ACCEPTED", "0.00"),
        _Trade("SIM-TRADE-D", "REJECTED", "999.00", rejection_reason="WRONG_SIGN"),
        _Trade("SIM-TRADE-E", "DUPLICATE", "100.00"),
        _Trade("SIM-TRADE-F", "MATURED", "5.00"),
    ]
    # Hand-derived expected accepted total: 100.00 - 40.00 + 0.00 = 60.00
    manifest = compute_source_control_manifest(trades, manifest_id="SIM-MANIFEST-HAND-DERIVED")
    assert manifest.expected_accepted_count == 3
    assert manifest.expected_accepted_mtm_total.amount == Decimal("60.00")
    assert manifest.expected_rejected_count == 1
    assert manifest.expected_duplicate_count == 1
    assert manifest.expected_matured_count == 1
    assert manifest.rejection_reason_counts == (("WRONG_SIGN", 1),)


def test_reference_manifest_on_the_generated_300_trade_corpus_is_internally_consistent():
    corpus = build_trade_corpus()
    manifest = compute_source_control_manifest(
        corpus.trades,
        manifest_id="SIM-MANIFEST-TRADES-001",
        expected_missing_trade_ids=corpus.expected_missing_trade_ids,
    )
    total = (
        manifest.expected_accepted_count
        + manifest.expected_rejected_count
        + manifest.expected_duplicate_count
        + manifest.expected_matured_count
        + manifest.expected_cancelled_count
        + manifest.expected_amended_count
        + manifest.expected_unsupported_count
    )
    assert total == len(corpus.trades) == 300
    assert manifest.expected_missing_trade_ids == corpus.expected_missing_trade_ids


def test_reference_raises_if_a_missing_id_is_actually_present():
    corpus = build_trade_corpus()
    present_id = corpus.trades[0].trade_id
    import pytest

    with pytest.raises(ValueError):
        compute_source_control_manifest(
            corpus.trades,
            manifest_id="SIM-MANIFEST-BAD",
            expected_missing_trade_ids=(present_id,),
        )
